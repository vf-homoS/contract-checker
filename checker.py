"""
checker.py - "мозг" программы.

Здесь лежат все правила проверки договора. Каждое правило - это маленький
вопрос к тексту, например: "Есть ли в договоре раздел про ответственность?"
или "Нет ли в договоре фразы, что одна сторона может всё поменять сама?".
"""

import re
from dataclasses import dataclass

# Три уровня опасности. Чем выше - тем внимательнее надо читать.
HIGH = "ВЫСОКИЙ"
MEDIUM = "СРЕДНИЙ"
LOW = "НИЗКИЙ"

LEVEL_ORDER = {HIGH: 0, MEDIUM: 1, LOW: 2}


@dataclass
class Finding:
    """Одна находка: что нашли, насколько это опасно и почему."""
    level: str
    title: str
    explanation: str
    quote: str = ""      # кусочек текста договора, где нашли
    line_no: int = 0     # номер строки (0 - значит "в тексте этого нет")


# ---------------------------------------------------------------------------
# Правило 1. Обязательные разделы.
# Если в договоре нет раздела, который должен быть, - это находка.
# Формат: (название, шаблон поиска, уровень, объяснение простыми словами)
# ---------------------------------------------------------------------------
REQUIRED_SECTIONS = [
    ("Предмет договора",
     r"предмет\s+договора",
     HIGH,
     "Не написано, о чём вообще договор. Без этого нельзя понять, что именно "
     "одна сторона должна сделать для другой."),
    ("Цена и порядок расчётов",
     r"цена|стоимост|порядок\s+расч",
     HIGH,
     "Не видно, сколько стоит работа и когда нужно платить. Из-за этого легко "
     "поспорить о деньгах."),
    ("Сроки",
     r"срок\w*\s+(?:действия|выполнения|оказания|поставки)|срок\s+действия",
     HIGH,
     "Нет сроков. Непонятно, когда всё должно быть готово и когда договор "
     "заканчивается."),
    ("Ответственность сторон",
     r"ответственност",
     HIGH,
     "Нет раздела про ответственность. Если одна сторона подведёт, неясно, что "
     "ей за это будет."),
    ("Порядок расторжения",
     r"расторжен|прекращен",
     MEDIUM,
     "Не описано, как можно закончить договор раньше срока. Выйти из него "
     "потом будет сложно."),
    ("Разрешение споров",
     r"спор|подсудн|арбитраж",
     MEDIUM,
     "Не сказано, где и как решать споры. Придётся договариваться уже в ссоре."),
    ("Реквизиты сторон",
     r"реквизит|юридическ\w+\s+адрес|р/с|расч[её]тн\w+\s+счёт|расч[её]тн\w+\s+счет",
     MEDIUM,
     "Нет реквизитов (адреса, счёта, ИНН). Непонятно, кто именно подписал "
     "договор и куда платить."),
    ("Форс-мажор (обстоятельства непреодолимой силы)",
     r"форс-?мажор|непреодолим\w+\s+сил",
     LOW,
     "Нет пункта про непредвиденные события (наводнение, запрет властей и т. п.). "
     "Желательно его добавить, чтобы не отвечать за то, на что не повлиять."),
    ("Конфиденциальность",
     r"конфиденциальн|коммерческ\w+\s+тайн",
     LOW,
     "Нет пункта о сохранении секретов. Если стороны обмениваются важной "
     "информацией, лучше защитить её."),
]

# ---------------------------------------------------------------------------
# Правило 2. Опасные фразы.
# Формат: (шаблон поиска, уровень, название, объяснение)
# ---------------------------------------------------------------------------
RISKY_PHRASES = [
    (r"в\s+одностороннем\s+порядке",
     MEDIUM,
     "Одна сторона может решать сама",
     "Фраза «в одностороннем порядке» значит, что одна сторона может что-то "
     "изменить или отменить без согласия второй. Проверь, кому это разрешено: "
     "если не тебе, это риск."),
    (r"без\s+(?:предварительного\s+)?(?:уведомлени|согласовани|согласи)",
     MEDIUM,
     "Действия «без предупреждения»",
     "Что-то можно сделать, не сообщив второй стороне. Лучше, чтобы о важных "
     "вещах предупреждали заранее."),
    (r"автоматическ\w+\s+(?:пролонг|продлева|продлен)|пролонгируется|"
     r"продлевается\s+на\s+(?:тот\s+же|каждый)",
     MEDIUM,
     "Договор продлевается сам",
     "Если вовремя не отказаться, договор начнёт действовать ещё один срок. "
     "Легко пропустить дату и застрять в договоре."),
    (r"по\s+(?:своему\s+)?усмотрени\w+",
     LOW,
     "Размытое право «по усмотрению»",
     "Слова «по усмотрению» дают одной стороне свободу решать как угодно. "
     "Лучше записать понятные правила."),
    (r"не\s+несёт\s+(?:какой-либо\s+)?ответственност|не\s+несет\s+(?:какой-либо\s+)?ответственност|"
     r"освобождается\s+от\s+(?:любой\s+)?ответственност",
     HIGH,
     "Сторона снимает с себя ответственность",
     "Одна сторона заранее записала, что ни за что не отвечает. Это может "
     "оставить вторую без защиты, если что-то пойдёт не так."),
    (r"без\s+ограничени\w+\s+(?:размер|ответственност|суммы)|в\s+полном\s+объ[её]ме\s+убытк",
     MEDIUM,
     "Ответственность без предела",
     "Сумма, которую придётся заплатить за ошибку, ничем не ограничена. "
     "Это может обойтись очень дорого."),
    (r"безвозвратн|не\s+подлежат?\s+возврат|возврату\s+не\s+подлежат?",
     HIGH,
     "Деньги не вернут",
     "Если что-то сорвётся, уплаченные деньги назад не получить."),
    (r"исключительн\w+\s+(?:право|прав)",
     MEDIUM,
     "Передача исключительных прав",
     "Все права на результат уходят одной стороне. Убедись, что ты на это "
     "согласен и что за это справедливо платят."),
    (r"бессрочн",
     MEDIUM,
     "Договор без срока",
     "Договор действует неопределённо долго. Проверь, как из него можно выйти."),
    (r"штраф\w*\s+(?:в\s+размере\s+)?\d[\d\s]*(?:руб|₽)",
     LOW,
     "Фиксированный штраф",
     "Есть штраф в твёрдой сумме. Посмотри, не слишком ли она велика для "
     "размера договора и одинаково ли штрафуют обе стороны."),
]

# ---------------------------------------------------------------------------
# Правило 3. Недозаполненные места: «____», «[ФИО]», «<дата>», «ХХХ».
# ---------------------------------------------------------------------------
PLACEHOLDER_RE = re.compile(r"_{3,}|\[[^\]\n]*\]|<[^>\n]*>|\bх{3,}\b|\.{5,}", re.IGNORECASE)

# ---------------------------------------------------------------------------
# Правило 4. Неустойка (пени за просрочку) - проверяем процент в день.
# ---------------------------------------------------------------------------
PENALTY_RE = re.compile(
    r"(\d+(?:[.,]\d+)?)\s*%[^.\n]{0,80}?за\s+(?:каждый|кажд\w+)\s+(?:календарный\s+)?(?:день|дн\w*)",
    re.IGNORECASE,
)

# ---------------------------------------------------------------------------
# Правило 5. Предоплата 100 %.
# ---------------------------------------------------------------------------
PREPAY_RE = re.compile(r"(?:предоплат\w*|аванс\w*)[^.\n]{0,40}?100\s*%|100\s*%[^.\n]{0,40}?(?:предоплат\w*|аванс\w*)",
                       re.IGNORECASE)

# ---------------------------------------------------------------------------
# Правило 6. ИНН: проверяем длину и контрольную цифру.
# ---------------------------------------------------------------------------
INN_RE = re.compile(r"ИНН\D{0,6}(\d+)", re.IGNORECASE)


def inn_is_valid(inn: str) -> bool:
    """Проверка ИНН по контрольным цифрам (как делает налоговая)."""
    if not inn.isdigit():
        return False
    d = [int(c) for c in inn]
    if len(d) == 10:
        k = [2, 4, 10, 3, 5, 9, 4, 6, 8]
        return sum(a * b for a, b in zip(k, d[:9])) % 11 % 10 == d[9]
    if len(d) == 12:
        k1 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        k2 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        n1 = sum(a * b for a, b in zip(k1, d[:10])) % 11 % 10
        n2 = sum(a * b for a, b in zip(k2, d[:11])) % 11 % 10
        return n1 == d[10] and n2 == d[11]
    return False


def _short(text: str, limit: int = 160) -> str:
    """Укорачиваем длинную строку, чтобы отчёт не распухал."""
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


def check_contract(text: str) -> list:
    """Главная функция: берёт текст договора, возвращает список находок."""
    findings = []
    lines = text.splitlines()

    # --- 1. Обязательные разделы ---
    for title, pattern, level, explanation in REQUIRED_SECTIONS:
        if not re.search(pattern, text, re.IGNORECASE):
            findings.append(Finding(level, f"Не найден раздел: {title}", explanation))

    # --- 2. Опасные фразы (по каждой строке) ---
    for pattern, level, title, explanation in RISKY_PHRASES:
        for number, line in enumerate(lines, start=1):
            if re.search(pattern, line, re.IGNORECASE):
                findings.append(Finding(level, title, explanation, _short(line), number))

    # --- 3. Пустые места для заполнения ---
    for number, line in enumerate(lines, start=1):
        if PLACEHOLDER_RE.search(line):
            findings.append(Finding(
                MEDIUM,
                "Не заполнено место в договоре",
                "Здесь остался пропуск или заготовка (например, «____» или «[ФИО]»). "
                "Договор нельзя подписывать, пока всё не заполнено.",
                _short(line), number))

    # --- 4. Размер неустойки ---
    for number, line in enumerate(lines, start=1):
        for match in PENALTY_RE.finditer(line):
            percent = float(match.group(1).replace(",", "."))
            if percent >= 1:
                level, how = HIGH, "очень большой"
            elif percent > 0.1:
                level, how = MEDIUM, "выше обычного"
            else:
                continue
            findings.append(Finding(
                level,
                f"Неустойка {percent:g}% за каждый день - размер {how}",
                f"За каждый день просрочки придётся платить {percent:g}% от суммы. "
                f"За 30 дней это уже около {percent * 30:g}% от суммы. Обычно "
                "берут около 0,1% в день, так что проверь, справедливо ли это.",
                _short(line), number))

    # --- 5. Предоплата 100 % ---
    for number, line in enumerate(lines, start=1):
        if PREPAY_RE.search(line):
            findings.append(Finding(
                HIGH,
                "Предоплата 100%",
                "Всю сумму надо заплатить до начала работы. Если вторая сторона "
                "подведёт, вернуть деньги будет трудно. Безопаснее платить частями.",
                _short(line), number))

    # --- 6. Проверка ИНН ---
    for number, line in enumerate(lines, start=1):
        for match in INN_RE.finditer(line):
            inn = match.group(1)
            if len(inn) not in (10, 12):
                findings.append(Finding(
                    HIGH, "Неверная длина ИНН",
                    f"В ИНН должно быть 10 цифр (у организации) или 12 (у человека), "
                    f"а здесь {len(inn)}. Возможно, опечатка.",
                    _short(line), number))
            elif not inn_is_valid(inn):
                findings.append(Finding(
                    HIGH, "ИНН не проходит проверку",
                    "Последние цифры ИНН считаются по формуле, и здесь формула не "
                    "сходится. Скорее всего, в номере ошибка или он выдуман.",
                    _short(line), number))

    findings.sort(key=lambda f: (LEVEL_ORDER[f.level], f.line_no))
    return findings


def verdict(findings: list) -> str:
    """Короткий вывод по всему договору."""
    high = sum(1 for f in findings if f.level == HIGH)
    medium = sum(1 for f in findings if f.level == MEDIUM)
    if high >= 3:
        return "Договор рискованный. Лучше показать юристу до подписания."
    if high >= 1:
        return "Есть серьёзные замечания. Разберись с ними до подписания."
    if medium >= 1:
        return "Критичного мало, но есть что поправить."
    return "Явных проблем не найдено. Всё равно прочитай договор внимательно сам."


def format_report(findings: list, file_name: str = "") -> str:
    """Собираем отчёт в красивый текст."""
    out = []
    out.append("ОТЧЁТ О ПРОВЕРКЕ ДОГОВОРА")
    if file_name:
        out.append(f"Файл: {file_name}")
    out.append("=" * 60)

    high = sum(1 for f in findings if f.level == HIGH)
    medium = sum(1 for f in findings if f.level == MEDIUM)
    low = sum(1 for f in findings if f.level == LOW)
    out.append(f"Найдено замечаний: {len(findings)}  "
               f"(высокий: {high}, средний: {medium}, низкий: {low})")
    out.append(f"Вывод: {verdict(findings)}")
    out.append("=" * 60)

    if not findings:
        out.append("Замечаний нет.")

    for i, f in enumerate(findings, start=1):
        out.append("")
        out.append(f"{i}. [{f.level}] {f.title}")
        if f.line_no:
            out.append(f"   Строка {f.line_no}: «{f.quote}»")
        out.append(f"   Что это значит: {f.explanation}")

    out.append("")
    out.append("-" * 60)
    out.append("Важно: программа - помощник, а не юрист. Она ищет типичные "
               "ловушки, но не заменяет консультацию специалиста.")
    return "\n".join(out)
